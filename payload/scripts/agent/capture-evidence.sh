#!/usr/bin/env bash
# Usage: capture-evidence.sh <task-id> [extra playwright args, e.g. --grep "AC-2"]
# Runs .work/<task-id>/evidence/*.evidence.spec.ts with Playwright. The specs
# save screenshots into the same folder (they get its path as EVIDENCE_DIR).
# Prints a short summary only; the full output goes to logs/evidence.log.
# Re-capturing cancels any earlier approval, because the evidence has changed.
set -uo pipefail
source "$(dirname "$0")/config.sh"
require npx jq

TASK="${1:?usage: capture-evidence.sh <task-id> [playwright args]}"
shift
EV="$(task_dir "$TASK")/evidence"
LOG="$(task_dir "$TASK")/logs/evidence.log"
mkdir -p "$EV" "$(dirname "$LOG")"

if ! ls "$EV"/*.evidence.spec.ts >/dev/null 2>&1; then
  echo "No *.evidence.spec.ts in ${EV#"$REPO_ROOT"/}. Write one first." >&2
  exit 1
fi

js() { jq -rn --arg s "$1" '$s|@json'; }    # quote a value for the config file
W="${EVIDENCE_VIEWPORT%x*}"; H="${EVIDENCE_VIEWPORT#*x}"

storage=""
if [ -n "$EVIDENCE_STORAGE_STATE" ]; then
  state_path="$EVIDENCE_STORAGE_STATE"
  case "$state_path" in /*) ;; *) state_path="$REPO_ROOT/$state_path" ;; esac
  [ -f "$state_path" ] || { echo "EVIDENCE_STORAGE_STATE file not found: $state_path" >&2; exit 1; }
  storage="storageState: $(js "$state_path"),"
fi

server=""
if [ -n "$EVIDENCE_START_CMD" ]; then
  server="webServer: { command: $(js "$EVIDENCE_START_CMD"), url: $(js "$EVIDENCE_BASE_URL"), cwd: $(js "$REPO_ROOT"), reuseExistingServer: true, timeout: 180_000 },"
fi

# Regenerated every run from .agent.env, so don't edit it by hand.
cat > "$EV/playwright.evidence.config.ts" <<EOF
// Generated by scripts/agent/capture-evidence.sh. Edit .agent.env instead.
import { defineConfig } from '@playwright/test';
export default defineConfig({
  testDir: '.',
  testMatch: '*.evidence.spec.ts',
  outputDir: './test-results',
  timeout: 60_000,
  retries: 0,
  workers: 1,
  reporter: [['line']],
  use: {
    baseURL: $(js "$EVIDENCE_BASE_URL"),
    viewport: { width: $W, height: $H },
    $storage
    screenshot: 'off',
    video: 'off',
    trace: 'retain-on-failure',
  },
  $server
});
EOF

rm -f "$EV/APPROVED"
start=$(date +%s)
(cd "$REPO_ROOT" && EVIDENCE_DIR="$EV" CI=1 NO_COLOR=1 FORCE_COLOR=0 \
  npx playwright test --config "$EV/playwright.evidence.config.ts" "$@") > "$LOG" 2>&1
code=$?
secs=$(( $(date +%s) - start ))

if [ "$code" -eq 0 ]; then
  echo "PASS  evidence specs (${secs}s)"
else
  echo "FAIL  evidence specs (exit $code, ${secs}s). Full log: ${LOG#"$REPO_ROOT"/}"
  grep -nE '(✘|[0-9]+\) |Error|Timeout|expect\(|locator)' "$LOG" | head -n "$FAIL_TAIL_LINES" | cut -c1-240 | sed 's/^/      /'
fi

shots=$(find "$EV" -maxdepth 1 -name '*.png' | sort)
if [ -z "$shots" ]; then
  echo "No screenshots in ${EV#"$REPO_ROOT"/}. The specs must save to process.env.EVIDENCE_DIR."
  exit 1
fi
echo "Screenshots:"
while read -r f; do
  echo "  $(basename "$f")  ($(( $(wc -c < "$f") / 1024 )) KB)"
done <<<"$shots"
exit "$code"
